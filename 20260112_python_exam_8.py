# 문제1 : 리스트에 2, 1, 5, 6, 7를 담고, for문으로 요소 전부 출력, len 사용
nums = [2, 1, 5, 6, 7]
l = len(nums)
for i in range(l):
    print(nums[i])

print("====================================================")
# 문제2 : 리스트에 2, 1, 5, 6, 7를 담고, for문으로 요소들을 역순으로 출력, len 사용
nums = [2, 1, 5, 6, 7]
l = len(nums)
for i in range(l - 1, -1, -1):
    print(nums[i])
print("====================================================")
# 문제3 : 리스트에 각 달의 끝 날짜들을 담고, '1월은 31일까지'와 같은 양식으로 출력
