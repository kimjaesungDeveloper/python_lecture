# 문제4 : 리스트에 각 달의 끝 날짜들을 담고, '1월은 31일까지'와 같은 양식으로 출력, len 사용
end_day = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
print("날짜 : ", len(end_day))
for i in range(len(end_day)):
    print(f"{i+1}월은 {end_day[i-1]}일까지")
print("====================================================")
# 문제5 : 리스트에 각 달의 끝 날짜들을 담고, '1월은 31일까지'와 같은 양식으로 출력, enumerate 사용
end_day = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

for mon, day in enumerate(end_day):
    print(f"{mon+1}월은 {day}일까지")
print("====================================================")
